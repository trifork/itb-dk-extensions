package com.trifork.itb.plugin;

import static org.junit.jupiter.api.Assertions.*;

import java.net.URI;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Clock;
import java.time.Duration;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;
import javax.xml.transform.TransformerFactory;
import javax.xml.transform.dom.DOMSource;
import javax.xml.transform.stream.StreamResult;
import javax.xml.xpath.XPathConstants;
import javax.xml.xpath.XPathFactory;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfSystemProperty;
import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.Node;

/**
 * Checks the QRD/QFDD comparison against every real form in the SPGDEF catalogue, using responses
 * generated by {@link QrdGenerator}. Opt-in, like {@link SpgdefLiveTest}: {@code mvn test
 * -Dtest=SpgdefCorpusLiveTest -Dcda.live.spgdef=true}. With {@code -Dcda.live.spgdef.out=<dir>} the
 * generated responses are also written there.
 */
@EnabledIfSystemProperty(named = "cda.live.spgdef", matches = "true")
class SpgdefCorpusLiveTest {

    private static final HttpQfddFetcher FETCHER = new HttpQfddFetcher(10_000, 30_000);
    private static final SpgdefQfddResolver RESOLVER =
            new SpgdefQfddResolver(FETCHER, Clock.systemUTC(), Duration.ofMinutes(30));

    /**
     * Published forms whose own definition makes the comparison fail, and exactly what it reports.
     * The form defines question 3101 twice, so no response id can identify one question.
     */
    private static final Map<String, Set<String>> DEFECTIVE_FORMS =
            Map.of(
                    "edeff356-49cc-47a6-9ebf-abf0057eba90",
                    Set.of("PRO-PAIR-QUESTION-ID", "PRO-PAIR-ANSWER-DUPLICATE"));

    private static Map<String, URI> catalogue() throws Exception {
        var response = FETCHER.get(SpgdefQfddResolver.INDEX, SpgdefQfddResolver.MAX_INDEX_BYTES);
        return SpgdefQfddResolver.parseCatalogue(
                new String(response.body(), StandardCharsets.UTF_8));
    }

    @Test
    void everyRealFormGetsAConsistentResponse() throws Exception {
        String out = System.getProperty("cda.live.spgdef.out");
        List<String> problems = new ArrayList<>();
        for (String id : catalogue().keySet()) {
            byte[] qfdd = RESOLVER.resolve(id, null).document();
            QrdGenerator.Result result = QrdGenerator.consistentResponse(qfdd);
            if (out != null) {
                Files.write(Path.of(out).resolve(id + ".xml"), result.qrd());
            }
            Set<String> expected = DEFECTIVE_FORMS.getOrDefault(id, Set.of());
            for (Finding finding : result.findings()) {
                boolean failure =
                        finding.level == Finding.Level.ERROR
                                || finding.level == Finding.Level.WARNING;
                if (failure && !expected.contains(finding.assertionId)) {
                    problems.add(
                            id
                                    + " ("
                                    + result.rounds()
                                    + " rounds): "
                                    + finding.level
                                    + " "
                                    + finding.assertionId
                                    + " "
                                    + finding.description);
                }
            }
        }
        assertTrue(
                problems.isEmpty(),
                problems.size()
                        + " finding(s):\n"
                        + String.join("\n", problems.subList(0, Math.min(problems.size(), 40))));
    }

    // XPath 1.0 (the JDK's engine), hence the chain of "or".
    private static final String ANSWERS =
            "//*[local-name()='observation'][*[local-name()='templateId'"
                    + "][@root='2.16.840.1.113883.10.20.33.4.4'"
                    + " or @root='2.16.840.1.113883.10.20.33.4.5'"
                    + " or @root='2.16.840.1.113883.10.20.33.4.6'"
                    + " or @root='2.16.840.1.113883.10.20.33.4.7'"
                    + " or @root='2.16.840.1.113883.10.20.33.4.8']]";

    private static Node first(Document document, String xpath) throws Exception {
        return (Node)
                XPathFactory.newInstance()
                        .newXPath()
                        .evaluate(xpath, document, XPathConstants.NODE);
    }

    private static byte[] bytes(Document document) throws Exception {
        var out = new java.io.ByteArrayOutputStream();
        TransformerFactory.newInstance()
                .newTransformer()
                .transform(new DOMSource(document), new StreamResult(out));
        return out.toByteArray();
    }

    private static Set<String> ids(byte[] qfdd, byte[] qrd) {
        QfddResolver resolver = (id, version) -> QfddLookup.found(qfdd, "test corpus");
        Set<String> ids = new java.util.HashSet<>();
        for (Finding finding : QrdQfddPairRules.validate(qrd, resolver)) {
            ids.add(finding.assertionId);
        }
        return ids;
    }

    /**
     * The rules must still notice real problems in real forms, not only stay quiet on good data.
     */
    @Test
    void mutatedResponsesAreStillDetected() throws Exception {
        List<String> misses = new ArrayList<>();
        int mandatory = 0;
        int ranged = 0;
        for (String id : catalogue().keySet()) {
            if (DEFECTIVE_FORMS.containsKey(id)) {
                continue;
            }
            byte[] qfdd = RESOLVER.resolve(id, null).document();
            byte[] good = QrdGenerator.consistentResponse(qfdd).qrd();

            Document wrongOption = SecureXml.parse(good);
            Node value =
                    first(
                            wrongOption,
                            ANSWERS
                                    + "[*[local-name()='templateId']/@root='2.16.840.1.113883.10.20.33.4.5']/*[local-name()='value']");
            if (value != null) {
                ((Element) value).setAttribute("code", "NOT-AN-OPTION");
                if (!ids(qfdd, bytes(wrongOption)).contains("PRO-PAIR-ANSWER-OPTION")) {
                    misses.add(id + ": an unknown option was not reported");
                }
            }

            Document twice = SecureXml.parse(good);
            Node answer = first(twice, ANSWERS);
            answer.getParentNode().appendChild(answer.cloneNode(true));
            if (!ids(qfdd, bytes(twice)).contains("PRO-PAIR-ANSWER-DUPLICATE")) {
                misses.add(id + ": a duplicated answer was not reported");
            }

            Document unanswered = SecureXml.parse(good);
            Node required =
                    first(
                            unanswered,
                            ANSWERS
                                    + "[*[local-name()='entryRelationship']/*[local-name()='observation']/*[local-name()='value']/*[local-name()='low']/@value >= 1]");
            if (required != null) {
                mandatory++;
                required.getParentNode().getParentNode().removeChild(required.getParentNode());
                if (!ids(qfdd, bytes(unanswered)).contains("PRO-PAIR-ANSWER-MISSING")) {
                    misses.add(id + ": a missing mandatory answer was not reported");
                }
            }

            Document outside = SecureXml.parse(good);
            Node numeric =
                    first(
                            outside,
                            "//*[local-name()='observation'][*[local-name()='templateId']"
                                    + "[@root='2.16.840.1.113883.10.20.33.4.4']]"
                                    + "[not(*[local-name()='templateId'][@root='2.16.840.1.113883.10.20.33.4.7'])]"
                                    + "[*[local-name()='referenceRange']]");
            if (numeric != null) {
                Element number = null;
                for (Node n = numeric.getFirstChild(); n != null; n = n.getNextSibling()) {
                    if (n instanceof Element e && "value".equals(e.getLocalName())) {
                        number = e;
                    }
                }
                if (number != null) {
                    ranged++;
                    boolean date =
                            number.getAttributeNS(
                                            "http://www.w3.org/2001/XMLSchema-instance", "type")
                                    .endsWith("TS");
                    number.setAttribute("value", date ? "19000101" : "99999999");
                    if (!ids(qfdd, bytes(outside)).contains("PRO-PAIR-NUMERIC-RANGE")) {
                        misses.add(id + ": an out-of-range numeric answer was not reported");
                    }
                }
            }
        }
        assertTrue(mandatory > 0, "the corpus should contain mandatory questions");
        assertTrue(ranged > 0, "the corpus should contain numeric questions with a range");
        assertTrue(
                misses.isEmpty(),
                misses.size() + " undetected mutation(s):\n" + String.join("\n", misses));
    }
}
